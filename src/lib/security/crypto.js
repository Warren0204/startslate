/**
 * @file src/lib/security/crypto.js
 * @description AES-256-GCM field-level PII encryption/decryption, token hashing, and HMAC-SHA256 webhook signatures.
 */

import crypto from 'node:crypto';

const AES_ALGORITHM = 'aes-256-gcm';
const IV_BYTE_LENGTH = 12;
const AUTH_TAG_BYTE_LENGTH = 16;
const PAYLOAD_VERSION = 'v1';
const HEX_64_REGEX = /^[0-9a-fA-F]{64}$/;

/**
 * Custom error thrown when encryption key configuration is missing or malformed.
 *
 * @description Indicates a server environment misconfiguration for cryptographic keys.
 */
export class CryptoConfigError extends Error {
  /**
   * Creates a CryptoConfigError instance.
   *
   * @description Initializes a configuration error with HTTP 500 metadata.
   * @param {string} message - Explanation of the invalid key configuration.
   * @returns {CryptoConfigError} Constructed error instance.
   * @throws {Error} Never throws during construction.
   */
  constructor(message) {
    super(message);
    this.name = 'CryptoConfigError';
    this.code = 'CRYPTO_CONFIG_ERROR';
    this.statusCode = 500;
  }
}

/**
 * Custom error thrown when PII encryption, decryption, or signature verification fails.
 *
 * @description Signals tampered ciphertext, wrong authentication tag/AAD, or invalid cryptographic inputs.
 */
export class CryptoError extends Error {
  /**
   * Creates a CryptoError instance.
   *
   * @description Initializes a cryptographic operation failure carrying error code metadata.
   * @param {string} message - Human-readable error explanation.
   * @param {string} [code='CRYPTO_OPERATION_FAILED'] - Machine-readable error code.
   * @param {number} [statusCode=400] - Suggested HTTP status code.
   * @returns {CryptoError} Constructed error instance.
   * @throws {Error} Never throws during construction.
   */
  constructor(message, code = 'CRYPTO_OPERATION_FAILED', statusCode = 400) {
    super(message);
    this.name = 'CryptoError';
    this.code = code;
    this.statusCode = statusCode;
  }
}

/**
 * Loads and validates the 32-byte AES-256 master key from `process.env.PII_ENCRYPTION_KEY`.
 *
 * @description Reads `PII_ENCRYPTION_KEY` as a strict 64-character hex string and converts it to a 32-byte Buffer.
 * @param {string} [rawKey=process.env.PII_ENCRYPTION_KEY] - Optional key override for isolated tests.
 * @returns {Buffer} 32-byte cryptographic key buffer.
 * @throws {CryptoConfigError} Throws when `PII_ENCRYPTION_KEY` is missing or not exactly 64 hex characters.
 */
function resolveMasterKeyBuffer(rawKey = process.env.PII_ENCRYPTION_KEY) {
  if (typeof rawKey !== 'string' || !HEX_64_REGEX.test(rawKey.trim())) {
    throw new CryptoConfigError(
      'PII_ENCRYPTION_KEY must be configured as a 64-character hexadecimal string (32 bytes).'
    );
  }

  return Buffer.from(rawKey.trim(), 'hex');
}

/**
 * Encrypts sensitive PII plaintext using AES-256-GCM with a random 12-byte IV.
 *
 * @description Uses `aes-256-gcm` with `process.env.PII_ENCRYPTION_KEY` and optional Additional Authenticated Data (AAD), returning `v1:<ivHex>:<authTagHex>:<ciphertextHex>`.
 * @param {string} text - Sensitive plaintext string to encrypt (e.g., Government ID number).
 * @param {string} [aad=''] - Optional Additional Authenticated Data (e.g., `${orgId}:${hireId}`) bound to the GCM auth tag.
 * @returns {string} Versioned ciphertext envelope `v1:<ivHex>:<authTagHex>:<ciphertextHex>`.
 * @throws {CryptoConfigError} Throws if `PII_ENCRYPTION_KEY` is missing or malformed.
 * @throws {CryptoError} Throws if `text` is not a non-empty string.
 */
export function encryptPII(text, aad = '') {
  if (typeof text !== 'string' || text.length === 0) {
    throw new CryptoError('Plaintext PII value must be a non-empty string.', 'INVALID_PLAINTEXT', 400);
  }
  if (typeof aad !== 'string') {
    throw new CryptoError('Additional authenticated data (AAD) must be a string.', 'INVALID_AAD', 400);
  }

  const key = resolveMasterKeyBuffer();
  const iv = crypto.randomBytes(IV_BYTE_LENGTH);
  const cipher = crypto.createCipheriv(AES_ALGORITHM, key, iv, {
    authTagLength: AUTH_TAG_BYTE_LENGTH,
  });

  if (aad.length > 0) {
    cipher.setAAD(Buffer.from(aad, 'utf8'));
  }

  const encrypted = Buffer.concat([cipher.update(text, 'utf8'), cipher.final()]);
  const authTag = cipher.getAuthTag();

  return [
    PAYLOAD_VERSION,
    iv.toString('hex'),
    authTag.toString('hex'),
    encrypted.toString('hex'),
  ].join(':');
}

/**
 * Decrypts a versioned AES-256-GCM PII payload encrypted by `encryptPII`.
 *
 * @description Validates the `v1:<ivHex>:<authTagHex>:<ciphertextHex>` envelope, verifies the GCM authentication tag and optional AAD, and returns UTF-8 plaintext.
 * @param {string} payload - Encrypted payload envelope generated by `encryptPII`.
 * @param {string} [aad=''] - Optional Additional Authenticated Data matching the value supplied at encryption time.
 * @returns {string} Decrypted UTF-8 plaintext string.
 * @throws {CryptoConfigError} Throws if `PII_ENCRYPTION_KEY` is missing or malformed.
 * @throws {CryptoError} Throws DECRYPTION_FAILED (400) if payload format is invalid, auth tag fails, or AAD mismatches.
 */
export function decryptPII(payload, aad = '') {
  if (typeof payload !== 'string' || !payload.trim()) {
    throw new CryptoError('Encrypted PII payload must be a non-empty string.', 'INVALID_CIPHERTEXT', 400);
  }
  if (typeof aad !== 'string') {
    throw new CryptoError('Additional authenticated data (AAD) must be a string.', 'INVALID_AAD', 400);
  }

  const parts = payload.trim().split(':');
  if (parts.length !== 4 || parts[0] !== PAYLOAD_VERSION) {
    throw new CryptoError('Unsupported or malformed PII ciphertext envelope.', 'INVALID_CIPHERTEXT', 400);
  }

  const [, ivHex, authTagHex, ciphertextHex] = parts;
  if (
    !/^[0-9a-fA-F]{24}$/.test(ivHex) ||
    !/^[0-9a-fA-F]{32}$/.test(authTagHex) ||
    !/^[0-9a-fA-F]+$/.test(ciphertextHex) ||
    ciphertextHex.length % 2 !== 0
  ) {
    throw new CryptoError('Ciphertext envelope contains invalid hexadecimal segments.', 'INVALID_CIPHERTEXT', 400);
  }

  const key = resolveMasterKeyBuffer();
  const iv = Buffer.from(ivHex, 'hex');
  const authTag = Buffer.from(authTagHex, 'hex');
  const ciphertext = Buffer.from(ciphertextHex, 'hex');

  try {
    const decipher = crypto.createDecipheriv(AES_ALGORITHM, key, iv, {
      authTagLength: AUTH_TAG_BYTE_LENGTH,
    });
    if (aad.length > 0) {
      decipher.setAAD(Buffer.from(aad, 'utf8'));
    }
    decipher.setAuthTag(authTag);

    const decrypted = Buffer.concat([decipher.update(ciphertext), decipher.final()]);
    return decrypted.toString('utf8');
  } catch {
    throw new CryptoError(
      'Unable to decrypt PII payload: authentication tag or key mismatch.',
      'DECRYPTION_FAILED',
      400
    );
  }
}

/**
 * Produces a masked display string for sensitive identifiers (e.g., Government ID numbers).
 *
 * @description Masks all leading characters with asterisks while keeping up to `visibleTrailing` trailing characters.
 * @param {string} value - Sensitive identifier string.
 * @param {number} [visibleTrailing=4] - Number of trailing characters to leave unmasked.
 * @returns {string} Masked representation (e.g., `****6789`).
 * @throws {Error} Never throws; non-string or short values safely return masked asterisks.
 */
export function maskPII(value, visibleTrailing = 4) {
  if (typeof value !== 'string' || !value.trim()) {
    return '****';
  }
  const clean = value.trim();
  const keep = Math.max(0, Math.min(visibleTrailing, clean.length - 1));
  if (keep === 0 || clean.length <= 4) {
    return '*'.repeat(Math.max(4, clean.length));
  }
  return `${'*'.repeat(clean.length - keep)}${clean.slice(-keep)}`;
}

/**
 * Generates a high-entropy URL-safe opaque token for passwordless candidate portals.
 *
 * @description Uses `crypto.randomBytes` encoded as unpadded base64url (default 256 bits).
 * @param {number} [byteLength=32] - Number of cryptographically random bytes.
 * @returns {string} URL-safe random token string.
 * @throws {CryptoError} Throws if `byteLength` is less than 16 bytes.
 */
export function generateOpaqueToken(byteLength = 32) {
  if (!Number.isInteger(byteLength) || byteLength < 16) {
    throw new CryptoError('Token byteLength must be an integer >= 16.', 'INVALID_TOKEN_LENGTH', 400);
  }
  return crypto.randomBytes(byteLength).toString('base64url');
}

/**
 * Hashes an opaque portal token using SHA-256 for safe database lookup storage.
 *
 * @description Produces a 64-character lowercase hex digest so raw portal tokens are never persisted at rest.
 * @param {string} rawToken - Raw opaque token received from a portal URL or generator.
 * @returns {string} Lowercase SHA-256 hex digest.
 * @throws {CryptoError} Throws if `rawToken` is empty or not a string.
 */
export function hashToken(rawToken) {
  if (typeof rawToken !== 'string' || rawToken.length === 0) {
    throw new CryptoError('Token input must be a non-empty string.', 'INVALID_TOKEN', 400);
  }
  return crypto.createHash('sha256').update(rawToken, 'utf8').digest('hex');
}

/**
 * Computes a salted SHA-256 hash of a client IP address for RA 10173 audit logging.
 *
 * @description Avoids persisting raw client IP addresses in `system_audit_logs` while preserving correlation capability.
 * @param {string} ipAddress - Client IPv4 or IPv6 address.
 * @param {string} [salt=process.env.AUDIT_IP_SALT || ''] - Optional server salt string.
 * @returns {string} Lowercase SHA-256 hex digest.
 * @throws {CryptoError} Throws if `ipAddress` is not a non-empty string.
 */
export function hashIpAddress(ipAddress, salt = process.env.AUDIT_IP_SALT || '') {
  if (typeof ipAddress !== 'string' || !ipAddress.trim()) {
    throw new CryptoError('IP address must be a non-empty string.', 'INVALID_IP_ADDRESS', 400);
  }
  return crypto.createHash('sha256').update(`${salt}:${ipAddress.trim()}`, 'utf8').digest('hex');
}

/**
 * Signs an outbound IT provisioning webhook payload with HMAC-SHA256.
 *
 * @description Computes HMAC-SHA256 over `${timestamp}.${rawBody}` and formats `t=<timestamp>,v1=<hex>` for `X-StartSlate-Signature`.
 * @param {string} secret - Organization's decrypted webhook signing secret.
 * @param {number|string} timestamp - Unix timestamp in seconds.
 * @param {string} rawBody - Exact JSON string payload transmitted in the POST body.
 * @returns {string} Formatted `X-StartSlate-Signature` header value.
 * @throws {CryptoError} Throws if `secret`, `timestamp`, or `rawBody` is invalid.
 */
export function signWebhookPayload(secret, timestamp, rawBody) {
  if (typeof secret !== 'string' || !secret) {
    throw new CryptoError('Webhook signing secret must be a non-empty string.', 'INVALID_WEBHOOK_SECRET', 400);
  }
  if (timestamp === undefined || timestamp === null || String(timestamp).trim() === '') {
    throw new CryptoError('Webhook timestamp is required.', 'INVALID_WEBHOOK_TIMESTAMP', 400);
  }
  if (typeof rawBody !== 'string') {
    throw new CryptoError('Webhook rawBody must be a serialized string.', 'INVALID_WEBHOOK_BODY', 400);
  }

  const ts = String(timestamp).trim();
  const signatureHex = crypto
    .createHmac('sha256', secret)
    .update(`${ts}.${rawBody}`, 'utf8')
    .digest('hex');

  return `t=${ts},v1=${signatureHex}`;
}

/**
 * Verifies an incoming or test `X-StartSlate-Signature` header in constant time.
 *
 * @description Parses `t=<ts>,v1=<hex>`, recomputes the expected HMAC-SHA256 signature, and compares buffers via `crypto.timingSafeEqual`.
 * @param {string} secret - Webhook signing secret.
 * @param {string} rawBody - Exact serialized HTTP request body string.
 * @param {string} signatureHeader - Header string formatted as `t=<timestamp>,v1=<hex>`.
 * @returns {boolean} True when signature is valid; otherwise false.
 * @throws {Error} Never throws on malformed headers; returns `false` safely on mismatch.
 */
export function verifyWebhookSignature(secret, rawBody, signatureHeader) {
  if (
    typeof secret !== 'string' ||
    !secret ||
    typeof rawBody !== 'string' ||
    typeof signatureHeader !== 'string'
  ) {
    return false;
  }

  const parts = Object.fromEntries(
    signatureHeader
      .split(',')
      .map((item) => item.trim().split('='))
      .filter((pair) => pair.length === 2)
  );

  if (!parts.t || !parts.v1 || !/^[0-9a-fA-F]{64}$/.test(parts.v1)) {
    return false;
  }

  const expectedHex = crypto
    .createHmac('sha256', secret)
    .update(`${parts.t}.${rawBody}`, 'utf8')
    .digest('hex');

  const actualBuf = Buffer.from(parts.v1, 'hex');
  const expectedBuf = Buffer.from(expectedHex, 'hex');

  if (actualBuf.length !== expectedBuf.length) {
    return false;
  }

  return crypto.timingSafeEqual(actualBuf, expectedBuf);
}
